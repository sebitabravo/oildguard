export type DictKey = keyof typeof dict;

/** Todas las claves del diccionario (para verificar cobertura EN/ES en tests). */
export function dictKeys(): DictKey[] {
  return Object.keys(dict) as DictKey[];
}

export type DictParams = Readonly<Record<string, string | number>>;

function formatCopy(copy: string, params?: DictParams): string {
  if (!params) return copy;
  return copy.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder,
  );
}

/** Busca una clave y reemplaza parámetros escalares (diccionario solo español). */
// Decisión S02 (colapso ES): cada entrada ya es su copia española y se lee
// directo; el idioma recibido se ignora como puente hasta que S04 borre el
// parámetro. Los textos desconocidos del backend no pasan por t: los ayudantes
// fuera del alcance S01/S02 los devuelven en verbo como paso honesto de dato
// foráneo, sin inventar traducción.
export function t(key: DictKey, params?: DictParams): string {
  return formatCopy(dict[key], params);
}
