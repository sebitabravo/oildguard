export const LANG_STORAGE_KEY = "oilguard-lang";

export function getInitialLang(): Lang {
  return "es";
}

export function persistLang(_lang: Lang): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, "es");
  } catch {
    /* se ignora: sin almacenamiento la interfaz sigue en español */
  }
  window.dispatchEvent(new CustomEvent("oilguard:lang", { detail: "es" }));
}

import { useState } from "preact/hooks";

// Solo español: siempre español; el cambiador se ignora hasta que S04 lo
// borre junto a las props lang.
export function useLang(): [Lang, (l: Lang) => void] {
  const [lang] = useState<Lang>("es");
  const setLang = (_next: Lang): void => {
    persistLang("es");
  };
  return [lang, setLang];
}

